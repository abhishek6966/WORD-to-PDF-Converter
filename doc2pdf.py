"""## Handle File Upload

### Subtask:
Implement the logic for the upload button, including displaying the UI, processing uploaded files, and updating button states.

**Reasoning**:
I need to import necessary modules, initialize a global list for uploaded files, call the UI setup function, and then define and attach the callback logic for the upload button to handle file uploads, save them, and update button states.
"""

from google.colab import files
from IPython.display import clear_output

# 2. Define a global variable for uploaded files
uploaded_files_queue = []

# 3. Call setup_ui() to get the widgets
output_area, upload_button, convert_button, download_button = setup_ui()

def on_upload_button_clicked(button):
    """
    Callback function to handle file uploads.
    """
    with output_area:
        clear_output(wait=True) # Clear previous outputs in this area
        print("Please select your .doc or .docx files to upload...")

        try:
            uploaded = files.upload()
        except Exception as e:
            print(f"An error occurred during file upload: {e}")
            return

        if not uploaded:
            print("No files were uploaded.")
            convert_button.disabled = True
            download_button.disabled = True
            return

        uploaded_files_queue.clear() # Clear previous uploads
        for filename, content in uploaded.items():
            # Save the uploaded file content to a temporary file
            with open(filename, 'wb') as f:
                f.write(content)
            uploaded_files_queue.append(filename)
            print(f"Uploaded and saved: {filename}")

        if uploaded_files_queue:
            convert_button.disabled = False # Enable convert button
            download_button.disabled = True # Disable download button until conversion
            print(f"Successfully uploaded {len(uploaded_files_queue)} file(s). Convert button is now enabled.")
        else:
            convert_button.disabled = True
            download_button.disabled = True
            print("No valid files were processed.")

# 5. Attach the callback function to the upload button
upload_button.on_click(on_upload_button_clicked)

# 6. Display the UI components
display(upload_button, convert_button, download_button, output_area)

"""## Trigger Conversion

### Subtask:
Implement the logic for the 'Ready to Convert' button. Once files are uploaded and this button is clicked, it will call the previously defined conversion function for each uploaded file, provide user feedback, and enable the download button.

**Reasoning**:
I will define the global list `converted_pdf_paths` and then implement the `on_convert_button_clicked` function to handle file conversions, update UI states, and provide feedback as specified in the instructions.
"""

converted_pdf_paths = [] # Global list to store paths of converted PDFs

def on_convert_button_clicked(button):
    """
    Callback function to handle file conversion.
    """
    global converted_pdf_paths

    with output_area:
        clear_output(wait=True)
        print("Starting conversion process...")
        converted_pdf_paths.clear() # Clear previous converted paths

        output_pdf_dir = "converted_pdfs"
        os.makedirs(output_pdf_dir, exist_ok=True)

        if not uploaded_files_queue:
            print("No files to convert. Please upload files first.")
            convert_button.disabled = True
            download_button.disabled = True
            return

        for input_filepath in uploaded_files_queue:
            try:
                pdf_path = convert_doc_to_pdf(input_filepath, output_pdf_dir)
                converted_pdf_paths.append(pdf_path)
                print(f"Converted '{input_filepath}' to '{pdf_path}'")
            except Exception as e:
                print(f"Failed to convert '{input_filepath}': {e}")

        if converted_pdf_paths:
            download_button.disabled = False
            print(f"\nConversion complete. {len(converted_pdf_paths)} file(s) converted. Download button is now enabled.")
        else:
            download_button.disabled = True
            print("\nConversion completed, but no files were successfully converted.")

# Attach the callback function to the convert button
convert_button.on_click(on_convert_button_clicked)

print("Conversion logic for 'Ready to Convert' button defined.")

"""## Provide Download and Restart

### Subtask:
After successful conversion, display a download button for the generated PDF file using `google.colab.files.download()`. Immediately after providing the download option, the interactive UI will reset, allowing the user to upload a new file and restart the conversion process for another document without needing to rerun the entire code cell.

**Reasoning**:
I will define the `on_download_button_clicked` function to handle downloading all converted PDF files, then reset the global queues and UI button states to prepare for new uploads, as per the subtask instructions.
"""

def on_download_button_clicked(button):
    """
    Callback function to handle downloading converted PDF files and resetting the UI.
    """
    global uploaded_files_queue, converted_pdf_paths

    with output_area:
        clear_output(wait=True)
        print("Starting downloads...")

        if not converted_pdf_paths:
            print("No PDFs available for download.")
            return

        for pdf_path in converted_pdf_paths:
            try:
                print(f"Downloading {os.path.basename(pdf_path)}...")
                files.download(pdf_path)
            except Exception as e:
                print(f"Failed to download {os.path.basename(pdf_path)}: {e}")

        # Reset for new uploads
        uploaded_files_queue.clear()
        converted_pdf_paths.clear()

        convert_button.disabled = True
        download_button.disabled = True

        clear_output(wait=True)
        print("Downloads complete. UI has been reset. Ready for new uploads.")

# Attach the callback function to the download button
download_button.on_click(on_download_button_clicked)

print("Download and UI reset logic defined.")

