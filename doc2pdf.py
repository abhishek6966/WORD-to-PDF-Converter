    download_button = widgets.Button(
        description='Download PDF',
        disabled=True, # Initially disabled until conversion is complete
        button_style='success',
        tooltip='Click to download the converted PDF file',
        icon='download'
    )

    # 7. Return all created widgets
    return output_area, upload_button, convert_button, download_button

